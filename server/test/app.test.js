import {test} from 'node:test';
import assert from 'node:assert/strict';
import request from 'supertest';
import bcrypt from 'bcryptjs';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {createApp} from '../app.js';

test('owner, project files, scoped keys, search, limits and explicit deletion',async t=>{
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'project-server-'));
 const {app,db}=createApp({dataDir:dir,username:'owner',passwordHash:bcrypt.hashSync('correct horse battery',4),maxBytes:1024,dailyLimit:3});
 t.after(()=>{db.close();fs.rmSync(dir,{recursive:true,force:true})});
 const owner=request.agent(app);
 await request(app).get('/api/v1/projects').expect(401);
 await owner.post('/api/v1/auth/login').send({username:'owner',password:'bad'}).expect(401);
 await owner.post('/api/v1/auth/login').set('Origin','https://evil.example').send({username:'owner',password:'correct horse battery'}).expect(403);
 await owner.post('/api/v1/auth/login').send({username:'owner',password:'correct horse battery'}).expect(200);
 const p=(await owner.post('/api/v1/projects').send({name:'Alpha'}).expect(201)).body;
 const p2=(await owner.post('/api/v1/projects').send({name:'Beta'}).expect(201)).body;
 const base=`/api/v1/projects/${p.id}`;
 await owner.post(base+'/folders').send({path:'src'}).expect(201);
 await owner.put(base+'/content').send({path:'src/index.js',content:'hello world'}).expect(200);
 await owner.put(base+'/content').send({path:'src/index.js',content:'accidental'}).expect(409);
 await owner.put(base+'/content').send({path:'../escape',content:'bad'}).expect(400);
 await owner.put(base+'/content').send({path:'run.exe',content:'bad'}).expect(400);
 await owner.put(base+'/content').send({path:'src/.env',content:'SECRET=example'}).expect(200);
 await owner.post(base+'/upload').field('path','src/large.txt').attach('file',Buffer.alloc(1025),'large.txt').expect(413);
 await owner.post(base+'/upload').field('path','src/upload.txt').attach('file',Buffer.from('uploaded'),'upload.txt').expect(201);
 await owner.post(base+'/upload').field('path','src/upload.txt').attach('file',Buffer.from('no overwrite'),'upload.txt').expect(409);
 assert.equal((await owner.get(base+'/search?q=hello&mode=content').expect(200)).body.items[0].path,'src/index.js');
 assert.equal((await owner.get(base+'/search?q=index&mode=name').expect(200)).body.total,1);
 const ro=(await owner.post('/api/v1/keys').send({name:'reader',projectId:p.id,permission:'readonly'}).expect(201)).body.token;
 const rw=(await owner.post('/api/v1/keys').send({name:'writer',projectId:p.id,permission:'readwrite'}).expect(201)).body;
 const auth=token=>({Authorization:`Bearer ${token}`});
 assert.equal((await request(app).get('/api/v1/projects').set(auth(ro)).expect(200)).body.items.length,1);
 await request(app).get(`/api/v1/projects/${p2.id}/tree`).set(auth(ro)).expect(403);
 const tree=(await request(app).get(base+'/tree').set(auth(ro)).expect(200)).body;
 assert(!tree.items.some(x=>x.path.includes('.env')));
 await request(app).get(base+'/content?path=src%2F.env').set(auth(ro)).expect(403);
 await request(app).put(base+'/content').set(auth(ro)).send({path:'src/index.js',content:'no',overwrite:true}).expect(403);
 await request(app).delete(base+'/files').set(auth(rw.token)).send({path:'src',confirm:'src'}).expect(403);
 await request(app).post(base+'/move').set(auth(rw.token)).send({from:'src',to:'moved'}).expect(403);
 await request(app).put(base+'/content').set(auth(rw.token)).send({path:'src/index.js',content:'updated',overwrite:true}).expect(200);
 assert.equal((await owner.get(base+'/content?path=src%2Findex.js').expect(200)).body.content,'updated');
 await owner.put(base+'/content').send({path:'unicode.txt',content:'abc🙂xyz'}).expect(200);
 const chunk=(await owner.get(base+'/content?path=unicode.txt&limit=5').expect(200)).body;
 assert.equal(chunk.content,'abc'); assert.equal(chunk.nextOffset,3);
 assert.equal((await owner.get(base+'/content?path=unicode.txt&offset=3&limit=5').expect(200)).body.content,'🙂x');
 await owner.post(base+'/move').send({from:'src/upload.txt',to:'src/renamed.txt'}).expect(200);
 await owner.delete(base+'/files').send({path:'src/renamed.txt',confirm:'wrong'}).expect(400);
 await owner.delete(base+'/files').send({path:'src/renamed.txt',confirm:'src/renamed.txt'}).expect(200);
 fs.symlinkSync(path.join(dir,'metadata.sqlite'),path.join(dir,'projects',p.id,'outside-link'));
 await owner.get(base+'/download?path=outside-link').expect(400);
 assert(!(await owner.get(base+'/tree').expect(200)).body.items.some(x=>x.path==='outside-link'));
 const exportRes=await owner.get(base+'/export').buffer(true).parse((res,done)=>{const chunks=[];res.on('data',chunk=>chunks.push(chunk));res.on('end',()=>done(null,Buffer.concat(chunks)))}).expect(200); assert.match(exportRes.headers['content-type'],/zip/); assert(!exportRes.body.includes(Buffer.from('src/.env'))); assert(exportRes.body.includes(Buffer.from('src/index.js')));
 assert((await owner.get('/api/v1/logs').expect(200)).body.items.length>0);
 await owner.delete('/api/v1/keys/'+rw.id).expect(200);
 await request(app).get(base+'/tree').set(auth(rw.token)).expect(401);
 await owner.patch(base).send({status:'completed'}).expect(200);
 await owner.delete(base).send({confirm:'wrong'}).expect(400);
 await owner.delete(base).send({confirm:'Alpha'}).expect(200);
 await owner.post('/api/v1/projects').send({name:'Third'}).expect(201);
 await owner.post('/api/v1/projects').send({name:'Fourth'}).expect(429);
 await owner.post('/api/v1/auth/logout').expect(200);
 await owner.get('/api/v1/projects').expect(401);
});
